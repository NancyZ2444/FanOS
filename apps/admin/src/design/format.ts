export function actionLabel(value: unknown): string {
  const raw = String(value || "");
  if (!raw) return "—";
  const segments = raw
    .split(/[.:/]/)
    .filter((s) => !["catalog", "console", "operations", "admin"].includes(s));
  return segments
    .map(
      (s) =>
        actions[s] ||
        valueLabels[s] ||
        (/[\u4e00-\u9fff]/.test(s) ? s : "业务操作"),
    )
    .join(" · ");
}
export function formatTime(value: unknown): string {
  if (!value) return "—";
  const raw = String(value);
  const date = new Date(
    /^\d{4}-\d\d-\d\dT\d\d:\d\d(?::\d\d(?:\.\d+)?)?$/.test(raw)
      ? raw + "Z"
      : raw,
  );
  if (Number.isNaN(date.getTime())) return "—";
  const parts = new Intl.DateTimeFormat("sv-SE", {
    timeZone: TIME_ZONE,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).format(date);
  return parts.replace(",", "");
}
export function displayValue(value: unknown): string {
  if (value === null || value === undefined || value === "") return "—";
  if (typeof value === "boolean") return value ? "是" : "否";
  if (Array.isArray(value)) return value.map(displayValue).join("、") || "—";
  if (typeof value === "object")
    return Object.entries(value)
      .map(([k, v]) => `${fieldLabels[k] || "补充信息"}：${displayValue(v)}`)
      .join("；");
  return valueLabels[String(value)] || String(value);
}
